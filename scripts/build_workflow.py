"""Generate the explicit nine-scene Actions graph. No nested dispatches."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = '''# Generated by scripts/build_workflow.py. Commit regenerated changes.
name: Story runners
on:
  workflow_dispatch:
    inputs:
      backend:
        type: choice
        options: [fixture, live]
        default: fixture
        description: Live inference executes inside these jobs, without child workflows
      profile:
        type: choice
        options: [balanced, expressive, small]
        default: balanced
      request_file:
        type: choice
        options: [silent-bell-full, harbor]
        default: silent-bell-full
      scene_limit:
        type: choice
        options: ['9', '3', '1']
        default: '9'
        description: Nine scenes is the full three-chapter test
permissions:
  contents: read
concurrency:
  group: story-runners
  cancel-in-progress: false
jobs:
'''


def build():
    blocks = [HEADER]
    jobs = []
    def job(key, title, task, needs=(), downloads=(), index=None, matrix=None, state_output=False):
        jobs.append(key)
        lines = [f'  {key}:', f'    name: {title}']
        if needs:
            lines.append('    needs: [' + ', '.join(needs) + ']')
        if index is not None:
            lines.append(f"    if: ${{{{ {index} < fromJSON(inputs.scene_limit) }}}}")
        lines += ['    runs-on: ubuntu-latest', '    timeout-minutes: 45']
        if matrix:
            lines += ['    strategy:', '      fail-fast: false', '      max-parallel: 3', '      matrix:', f'        character: ${{{{ fromJSON(needs.{matrix}.outputs.characters) }}}}']
        if state_output:
            lines += ['    outputs:', '      characters: ${{ steps.task.outputs.characters }}']
        lines += ['    steps:', '      - uses: actions/checkout@v4', '      - uses: ./.github/actions/setup-worker', '        with:', '          backend: ${{ inputs.backend }}']
        for artifact, path, pattern in downloads:
            lines += ['      - uses: actions/download-artifact@v4', '        with:', f'          {"pattern" if pattern else "name"}: {artifact}', f'          path: inputs/{path}']
        lines += ['      - name: Run scoped story task', '        id: task', '        env:', '          STORY_BACKEND: ${{ inputs.backend }}', '          STORY_PROFILE: ${{ inputs.profile }}', '          STORY_REQUEST: ${{ inputs.request_file }}']
        if matrix:
            lines += ['          STORY_CHARACTER: ${{ matrix.character }}']
        args = f'{task} --backend "$backend" --profile "$STORY_PROFILE" --request-file "$STORY_REQUEST"'
        if index is not None:
            args += f' --index {index}'
        if matrix:
            args += ' --character "$STORY_CHARACTER"'
        lines += ['        run: |', '          backend=fixture', '          if [ "$STORY_BACKEND" = live ]; then backend=worker; fi', f'          python -m storyforge.dag {args}']
        artifact_name = key + ('-${{ matrix.character }}' if matrix else '')
        lines += ['      - uses: actions/upload-artifact@v4', '        if: always()', '        with:', f'          name: {artifact_name}', '          path: out/', '          retention-days: 7', '          overwrite: true']
        blocks.append('\n'.join(lines) + '\n')
    job('prepare', 'Prepare request and literary retrieval', 'prepare')
    job('refine', 'Refine initial story prompt', 'refine', ['prepare'], [('prepare', 'state', False)])
    job('plan', 'Plan three chapters', 'plan', ['refine'], [('refine', 'state', False)], state_output=True)
    previous = 'plan'
    for i in range(9):
        p = f's{i+1:02}'
        label = f'Chapter {i//3+1} scene {i%3+1}'
        state = [(previous, 'state', False)]
        job(p+'_characters', label+' / character ${{ matrix.character }}', 'character', [previous], state, i, matrix=previous)
        job(p+'_direction', label+' / reconcile character choices', 'director', [previous, p+'_characters'], state+[(p+'_characters-*', 'characters', True)], i)
        job(p+'_draft', label+' / writer', 'writer', [previous, p+'_direction'], state+[(p+'_direction','direction',False)], i)
        job(p+'_edit', label+' / distinct writing', 'edit', [previous,p+'_draft'], state+[(p+'_draft','draft',False)], i)
        common = state+[(p+'_edit','edited',False)]
        job(p+'_story', label+' / story quality', 'story_review', [previous,p+'_draft',p+'_edit'], common+[(p+'_draft','draft',False)], i)
        job(p+'_memory', label+' / extract memory', 'memory', [previous,p+'_edit'], common, i)
        job(p+'_repair', label+' / repair if needed', 'repair', [previous,p+'_edit',p+'_story'], common+[(p+'_story','diagnosis',False)], i)
        repaired = state+[(p+'_repair','edited',False)]
        job(p+'_verify', label+' / verify final prose', 'verify', [previous,p+'_repair',p+'_story',p+'_draft'], repaired+[(p+'_story','diagnosis',False),(p+'_draft','draft',False)], i)
        job(p+'_final_memory', label+' / refresh memory if prose changed', 'memory_final', [previous,p+'_repair',p+'_memory'], repaired+[(p+'_memory','initial-memory',False)], i)
        job(p+'_memory_review', label+' / verify memory', 'memory_review', [previous,p+'_repair',p+'_final_memory'], repaired+[(p+'_final_memory','memory',False)], i)
        job(p+'_accept', label+(' / verify chapter and commit' if (i+1)%3==0 else ' / commit accepted state'), 'accept', [previous,p+'_repair',p+'_verify',p+'_final_memory',p+'_memory_review'], repaired+[(p+'_verify','story-review',False),(p+'_final_memory','memory',False),(p+'_memory_review','memory-review',False)], i, state_output=True)
        previous = p+'_accept'
    blocks.append('''  results:
    name: Collect outputs and checkpoints
    if: always()
    needs: [''' + ', '.join(jobs) + ''']
    runs-on: ubuntu-latest
    steps:
      - uses: actions/download-artifact@v4
        with:
          path: results/
      - uses: actions/upload-artifact@v4
        with:
          name: story-run-${{ github.run_id }}
          path: results/
          retention-days: 7
          overwrite: true
      - name: Summarize run
        env:
          JOB_RESULTS: ${{ toJSON(needs) }}
        run: |
          python - <<'PY'
          import json, os
          results = json.loads(os.environ['JOB_RESULTS'])
          failed = [k for k, v in results.items() if v['result'] in ['failure', 'cancelled']]
          print('Failed/cancelled jobs:', failed)
          if failed:
              raise SystemExit(1)
          PY
''')
    return '\n'.join(blocks)

if __name__ == '__main__':
    (ROOT / '.github/workflows/story.yml').write_text(build())
